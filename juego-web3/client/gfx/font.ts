const FIRST = 32;
const LAST = 126;
export const FONT_KEY = 'pixel';
export const FONT_CELL_W = 6;
export const FONT_CELL_H = 8;

/** Letras extra: [caracter, base ASCII, marca encima]. */
const EXTRA: [string, string, 'acute' | 'tilde' | 'diaeresis' | 'flip'][] = [
  ['á', 'a', 'acute'],
  ['é', 'e', 'acute'],
  ['í', 'i', 'acute'],
  ['ó', 'o', 'acute'],
  ['ú', 'u', 'acute'],
  ['ñ', 'n', 'tilde'],
  ['ü', 'u', 'diaeresis'],
  ['Á', 'A', 'acute'],
  ['É', 'E', 'acute'],
  ['Í', 'I', 'acute'],
  ['Ó', 'O', 'acute'],
  ['Ú', 'U', 'acute'],
  ['Ñ', 'N', 'tilde'],
  ['¡', '!', 'flip'],
  ['¿', '?', 'flip'],
];

function glyph(ch: string): number[] {
  const c = ch.charCodeAt(0) - FIRST;
  return ASCII_5X7.slice(c * 5, c * 5 + 5);
}

function accent(base: number[], mark: (typeof EXTRA)[number][2]): number[] {
  const cols = [...base];
  if (mark === 'flip')
    return cols.map((b) =>
      parseInt(b.toString(2).padStart(7, '0').split('').reverse().join(''), 2),
    );
  // Las minusculas empiezan en la fila 2; las mayusculas se comprimen una fila.
  const isUpper = cols.some((b) => (b & 0x01) !== 0);
  const body = isUpper ? cols.map((b) => ((b << 1) & 0x7e) | (b & 0x40)) : cols;
  const marks: Record<string, number[]> = {
    acute: [0, 0, 0, 1, 0],
    tilde: [0, 1, 1, 0, 1],
    diaeresis: [0, 1, 0, 1, 0],
  };
  const m = marks[mark] ?? [0, 0, 0, 0, 0];
  return body.map((b, i) => (b & ~0x01) | (m[i] ? 0x01 : 0));
}

export const FONT_CHARS = (() => {
  let s = '';
  for (let c = FIRST; c <= LAST; c++) s += String.fromCharCode(c);
  return s + EXTRA.map((e) => e[0]).join('');
})();

/** Crea la textura y registra la fuente en la cache de Phaser. */
export function registerPixelFont(scene: Phaser.Scene): void {
  if (scene.cache.bitmapFont.exists(FONT_KEY)) return;
  const perRow = 16;
  const rows = Math.ceil(FONT_CHARS.length / perRow);
  const tex = scene.textures.createCanvas(
    `${FONT_KEY}_tex`,
    perRow * FONT_CELL_W,
    rows * FONT_CELL_H,
  );
  if (!tex) throw new Error('No se pudo crear la textura de la fuente');
  const ctx = tex.getContext();
  ctx.fillStyle = '#ffffff';
  [...FONT_CHARS].forEach((ch, i) => {
    const extra = EXTRA.find((e) => e[0] === ch);
    const cols = extra ? accent(glyph(extra[1]), extra[2]) : glyph(ch);
    const ox = (i % perRow) * FONT_CELL_W;
    const oy = Math.floor(i / perRow) * FONT_CELL_H;
    cols.forEach((bits, x) => {
      for (let y = 0; y < 7; y++) if (bits & (1 << y)) ctx.fillRect(ox + x, oy + y, 1, 1);
    });
  });
  tex.refresh();
  const data = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: `${FONT_KEY}_tex`,
    width: FONT_CELL_W,
    height: FONT_CELL_H,
    chars: FONT_CHARS,
    charsPerRow: perRow,
    'spacing.x': 0,
    'spacing.y': 0,
    'offset.x': 0,
    'offset.y': 0,
    lineSpacing: 2,
  });
  scene.cache.bitmapFont.add(FONT_KEY, data);
}
